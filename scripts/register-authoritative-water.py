#!/usr/bin/env python3
"""Register nearest canonical hexsides to definitive authored vector water paths.
Candidates are evidence, not certified gameplay edges. Never guess from bitmap contours.
"""
from lxml import etree as ET
from collections import defaultdict
import json,math,re,pathlib
ROOT=pathlib.Path(__file__).resolve().parents[1];MAPS=ROOT/'maps'
b=json.load(open(MAPS/'kiev.json')); e=json.load(open(MAPS/'odessa-extension.json'))
C={c['id']:c for c in b['cells']+e['cells']}
# Normalize obsolete water edges, leaving unrelated gameplay schema unchanged.
for c in C.values():
 for direction,arr in list(c.get('tileEdges',{}).items()):
  c['tileEdges'][direction]=[v for v in (arr if isinstance(arr,list) else [arr]) if v.get('kind') not in ('river','majorRiver','coast','lake')]
 for direction,f in list(c.get('hexsideFeatures',{}).items()):
  if f.get('type') in ('river','majorRiver','coast','lake'): del c['hexsideFeatures'][direction]
# Segment geometry generated by authoritative calibrated engine.
# Save canonical side coordinates using shared engine to avoid independently guessing hex orientation.
import subprocess
js='''const T=require('./core/terrain_tiles');const P=require('./maps/composer');const fs=require('fs');const b=JSON.parse(fs.readFileSync('./maps/kiev.json'));const e=JSON.parse(fs.readFileSync('./maps/odessa-extension.json'));const c=P.compose(b,e);console.log(JSON.stringify(T.gridSegmentData(c,...T.gridRadii(c.geometry))));'''
p=subprocess.run(['node','-e',js],cwd=ROOT,capture_output=True,text=True,check=True)
edges=json.loads(p.stdout)
print('edge ex',edges[0])
ns='{http://www.inkscape.org/namespaces/inkscape}'
root=ET.parse(str(MAPS/'source/user-svg/kiev-odessa-main.svg')).getroot();layers={g.get(ns+'label'):g for g in root.iter() if g.get(ns+'groupmode')=='layer'}
num=r'[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[Ee][-+]?\d+)?'
token=re.compile(r'[A-Za-z]|'+num)
count={'M':2,'L':2,'T':2,'H':1,'V':1,'C':6,'S':4,'Q':4,'A':7,'Z':0}
def flatten(d):
 ts=token.findall(d);i=0;cmd=None;pos=(0,0);start=pos;points=[]
 while i<len(ts):
  if ts[i].isalpha():cmd=ts[i];i+=1
  if not cmd:break
  C=cmd.upper();n=count.get(C)
  if n is None:break
  if C=='Z':pos=start;points.append(pos);cmd=None;continue
  if i+n>len(ts):break
  try: vals=list(map(float,ts[i:i+n]))
  except:break
  i+=n;old=pos;relative=cmd.islower()
  if C=='H': pos=(vals[0]+(old[0] if relative else 0),old[1])
  elif C=='V':pos=(old[0],vals[0]+(old[1] if relative else 0))
  else:
   x,y=vals[-2:] if C!='A' else vals[-2:]
   pos=(x+(old[0] if relative else 0),y+(old[1] if relative else 0))
  if C=='M':start=pos
  points.append(pos)
  if C=='M':cmd='l' if relative else 'L'
 return points

def matmul(a,b):
 return (a[0]*b[0]+a[2]*b[1],a[1]*b[0]+a[3]*b[1],a[0]*b[2]+a[2]*b[3],a[1]*b[2]+a[3]*b[3],a[0]*b[4]+a[2]*b[5]+a[4],a[1]*b[4]+a[3]*b[5]+a[5])
def get_transform(node):
 mat=(1,0,0,1,0,0)
 for op,ns in re.findall(r'(translate|scale|matrix)\s*\(([^)]*)\)',node.get('transform','')):
  v=list(map(float,re.findall(num,ns)))
  if op=='translate':t=(1,0,0,1,v[0],v[1] if len(v)>1 else 0)
  elif op=='scale':t=(v[0],0,0,v[1] if len(v)>1 else v[0],0,0)
  else:t=tuple(v)
  mat=matmul(mat,t)
 return mat
def transform_point(x,y,m):return (m[0]*x+m[2]*y+m[4],m[1]*x+m[3]*y+m[5])
def shape_path(layer,node):
 parents=[];x=node
 while x is not None:
  parents.append(x)
  if x is layer:break
  x=x.getparent()
 mat=(1,0,0,1,0,0)
 for item in reversed(parents):mat=matmul(mat,get_transform(item))
 points=flatten(node.get('d',''))
 return [(x*96/25.4,y*96/25.4) for x,y in (transform_point(x,y,mat) for x,y in points)]
def segdist(p,a,b):
 vx=b[0]-a[0];vy=b[1]-a[1];t=max(0,min(1,((p[0]-a[0])*vx+(p[1]-a[1])*vy)/(vx*vx+vy*vy or 1)))
 return math.hypot(p[0]-a[0]-t*vx,p[1]-a[1]-t*vy)
register=[];unsupported=[]
for kind,layer_name in [('river','river-minor'),('majorRiver','river-major'),('coast','coasts')]:
 layer=layers[layer_name]
 for node in layer:
  if ET.QName(node.tag).localname!='path':continue
  points=shape_path(layer,node)
  if not points:continue
  reg=[]
  for edge in edges:
   mid=[(edge['a'][0]+edge['b'][0])/2,(edge['a'][1]+edge['b'][1])/2]
   ds=[segdist(mid,points[i],points[i+1]) for i in range(len(points)-1)]
   dist=min(ds) if ds else 9999
   if dist<=4.5:
    reg.append({'cellId':edge['cellId'],'dir':edge['dir'],'neighborId':edge.get('neighborId'), 'offsetPx':round(dist,2)})
  register.append({'sourceId':node.get('id'),'kind':kind,'points':len(points),'hexsideCandidates':reg,'status':'visually-aligned-with-user-vector; not-certified-for-gameplay'})
  if not reg:unsupported.append(node.get('id'))
# Store candidates only; no speculative rule certification.
e['authoritativeWaterEdgeCandidates']=register
e['v289SourceImportAudit']['waterHexsideCandidates']={k:sum(len(v['hexsideCandidates']) for v in register if v['kind']==k) for k in ('river','majorRiver','coast')}
e['v289SourceImportAudit']['waterUnmatchedPaths']=unsupported
(MAPS/'kiev.json').write_text(json.dumps(b,indent=2,ensure_ascii=False)+'\n');(MAPS/'odessa-extension.json').write_text(json.dumps(e,indent=2,ensure_ascii=False)+'\n')
print('candidates',e['v289SourceImportAudit']['waterHexsideCandidates'],'unmatched',unsupported)

const assert=require('node:assert/strict');
const fs=require('node:fs');
const crypto=require('node:crypto');
const B=JSON.parse(fs.readFileSync('maps/leningrad.json','utf8'));
const T=require('../core/terrain_tiles');
const svg=fs.readFileSync('exports-v312/leningrad.svg','utf8');
const routes=B.sourceWaterRoutes.filter(r=>r.kind==='coast');
assert.equal(routes.length,1);
assert.equal(routes[0].points.length,54);
assert.equal(B.sourceCoastRenderingMode,'source-path-coast-wavelets');
assert.equal(crypto.createHash('sha256').update(fs.readFileSync('maps/source/user-svg/leningrad-main.svg')).digest('hex'),'ea1c83d00eea0212c530b98fd794125959175ad9d1cfa067aef78d6d73502447');
assert.equal((svg.match(/class="source-coast-connected-wavelet-fringe"/g)||[]).length,1,'must have one continuous wavelet path');
assert.equal((svg.match(/class="source-authored-coast"/g)||[]).length,1,'must retain exact source boundary');
assert.equal((svg.match(/class="registered-shore-fringe"[^>]*data-water-kind="coast"/g)||[]).length,0,'individual hex-side ribbons forbidden');
assert.match(svg,/data-coast-source-vertices="54"/);
assert.match(svg,/data-coast-wavelet-samples="266"/);
assert.equal((svg.match(/class="source-authored-lake"/g)||[]).length,4);
assert.equal((svg.match(/class="svg-authored-river"/g)||[]).length,10);
const lie=B.cells.find(c=>c.id==='0208');
assert(lie);
assert.deepEqual(new Set(B.authoredShoreHexsides.filter(x=>x.cellId==='0208'&&x.kind==='coast').map(x=>x.dir)),new Set(['N','SW','NW']));
assert.equal(T.validate(B,{requireReciprocal:false}).errors.length,0);
console.log('PASS v312: exact 54-vertex Leningrad coast retained; one connected source-path wavelet; four lakes and ten rivers preserved');

'use strict';
const A=require('node:assert/strict');
const S=require('../core/scenario_starting_setup');
const I=require('../core/leningrad_starting_inventory');
const M=require('../maps/leningrad.json');
const C=require('../maps/counter-configs/leningrad.json');
const cfg=require('../maps/setup/leningrad.json');
const fs=require('node:fs');
const clone=x=>JSON.parse(JSON.stringify(x));
let assertions=0;
const eq=(a,b)=>{A.deepEqual(a,b);assertions++;};
const ok=(a)=>{A.ok(a);assertions++;};
function expectReject({map=M,spec=cfg,allocation=selected,positions=placements,config=C,inventory=I}={},regex){
 const r=S.validate({map,spec,allocation,placements:positions,counterConfig:config,inventory});
 eq(r.valid,false);eq(r.state,null);
 if(regex)ok(r.errors.some(s=>regex.test(s)),r.errors.join('\n'));
 return r;
}
const {inv,selected,placements,slotData,sides,allocReport}=require('./fixtures/leningrad-source-setup-v357');
ok(inv.valid);
eq(slotData.errors,[]);
eq(cfg.printedRearAnchors.map(a=>a.printed),I.sourceRearHexes);
const sharedSource=fs.readFileSync('core/scenario_starting_setup.js','utf8');
ok(!/\bleningrad\b/i.test(sharedSource));
ok(!/\bgerman\b|\bsoviet\b/i.test(sharedSource));
eq(sides.fixedInfantry,['0208','0707','1706']);
eq(sides.fixedMechanized,['1406','1802']);
eq(sides.cross,['0210','0310','0311','0411','0511']);
eq(sides.star,['0209','0309','0410','0510','0611']);
const args={map:M,spec:cfg,allocation:selected,placements,counterConfig:C,inventory:I};
const valid=S.validate(args);ok(valid.valid);ok(valid.physicalSetupValid);
eq(valid.state.scenarioId,'leningrad');eq(Object.keys(valid.state.units).length,19);
eq(valid.state.units[selected.sovietRearMechanizedCorps[0]].strengthStatus,'untried');eq(valid.state.units[selected.sovietRearMechanizedCorps[0]].printedCombatStrength,null);
ok(!valid.historicalSetupAuthorized);ok(!valid.productionGameActivated);ok(!valid.printedAnchorAgreement);
eq(valid.printedAnchorReport.length,5);
eq(valid.printedAnchorDisagreements.map(a=>[a.rulebookPrintedHex,a.physicalCellId,a.renderedNumber]),[['1305','1406','1306'],['1701','1802','1702']]);
for(const anchor of valid.printedAnchorReport){
 const data=fs.readFileSync('maps/source/user-svg/leningrad-main.svg','utf8');
 ok(data.includes(`id="${anchor.sourceSvgId}"`));
}
const shuffled=Object.fromEntries(Object.entries(placements).reverse());
eq(S.validate({...args,placements:shuffled}).state,valid.state);
const bad1=clone(placements);bad1[selected.sovietRearMechanizedCorps[0]]='1405';expectReject({positions:bad1},/Wrong source marker|Occupancy/);
const bad2=clone(placements);bad2[selected.germanInitialInfantry[0]]='0209';expectReject({positions:bad2},/Wrong source marker/);
const bad3=clone(placements);bad3[selected.germanInitialInfantry[0]]='0310';expectReject({positions:bad3},/Occupancy distribution/);
const bad4=clone(placements);bad4[selected.sovietFrontArmies[1]]='0309';expectReject({positions:bad4},/Forbidden adjacent|Occupancy distribution/);
const bad5=clone(placements);delete bad5[selected.sovietFrontArmies[0]];expectReject({positions:bad5},/Every starting face/);
const bad6=clone(placements);bad6[selected.germanTurn4Infantry[0]]='0210';expectReject({positions:bad6},/Non-starting|Every starting/);
const bad7=clone(placements);bad7[selected.germanInitialInfantry[0]]='0105';expectReject({positions:bad7},/Wrong source marker/);
const bad8=clone(selected);bad8.sovietRearInfantryCorps=selected.sovietRearInfantryCorps.slice(1);expectReject({allocation:bad8},/Incorrect starting group count/);
const bad9=clone(cfg);bad9.markerSlots.fixedMechanized.count=3;expectReject({spec:bad9},/Invalid marker capacity|Marker count/);
const bad10=clone(M);bad10.cells.find(c=>c.id==='1802').tileMarkers.find(t=>t.kind==='fixedMechanized').sourceSvgId='fake';expectReject({map:bad10},/Missing\/ambiguous SVG rear anchor/);
const bad11=clone(M);bad11.cells.find(c=>c.id==='0210').tileMarkers=[];expectReject({map:bad11},/Marker count|Occupancy distribution/);
const bad12=clone(C);bad12.faces.back.find(f=>f.faceId===valid.state.units[selected.sovietRearInfantryCorps[0]].reverseFaceId).pairedFaceId='fake';expectReject({config:bad12},/Missing movement\/paired counter face/);
expectReject({inventory:{inspect:()=>({valid:true,pools:inv.pools}),validateAllocation:()=>({valid:false})}},/Source-valid inventory/);
const bad13=clone(C);bad13.faces.front.find(f=>f.faceId===selected.sovietRearInfantryCorps[0]).visualTranscription.printedAffiliation='axis';expectReject({config:bad13},/Source-valid inventory|Unverified face|Counter face\/source group mismatch/);
const wrongMap=clone(M);wrongMap.sourceGame='other';expectReject({map:wrongMap},/Setup configuration\/map provenance mismatch/);
const altered=clone(valid.state);altered.units[selected.sovietRearInfantryCorps[0]].hex='0901';
eq(valid.state.units[selected.sovietRearInfantryCorps[0]].hex,placements[selected.sovietRearInfantryCorps[0]]);
console.log(`PASS v357 shared scenario starting setup: ${assertions} assertions; ${valid.startingUnitCount} real source faces staged; 2 printed-coordinate conflicts explicitly unresolved`);

'use strict';
const A=require('node:assert/strict');
const L=require('../maps/leningrad.json');
const P=require('../maps/movement-configs/leningrad.json');
const C=require('../maps/phase-configs/leningrad.json');
const K=require('../maps/counter-configs/leningrad.json');
const B=require('../core/movement_binding.js');
const R=require('../core/leningrad_setup_readiness.js');
const D=require('../core/historical_combat_declarations.js');
let checks=0;const yes=x=>{A.ok(x);checks++};
const report=R.inspect(L,K);
A.equal(report.ready,false);checks++;
A.equal(report.registered.stars.length,5);checks++;
A.equal(report.registered.crosses.length,4);checks++;
yes(report.gaps.some(x=>x.includes('cross source-mark count')));
yes(report.gaps.some(x=>x.includes('counter identities')));
A.equal(new Set(report.registered.stars.map(x=>x.hex)).size,5);checks++;
A.throws(()=>R.inspect({...L,sourceGame:'Wrong'},K),/Unexpected/);checks++;
const noCross={...L,authoredSvgImportAudit:{...L.authoredSvgImportAudit,details:{...L.authoredSvgImportAudit.details,deployment:L.authoredSvgImportAudit.details.deployment.filter(x=>x.kind!=='cross')}}};
const noCrossResult=R.inspect(noCross,K);A.equal(noCrossResult.registered.crosses.length,0);checks++;yes(!noCrossResult.ready);
const rig=D.create({map:L,profile:P,config:C});
const g=B.build(L,P).board;
const edge=g.edges.find(e=>!e.impassable&&!e.allSea&&!e.lake&&g.cells[e.a].verified&&g.cells[e.b].verified);
yes(edge);
const cursor={scenarioId:'leningrad',turn:1,index:2,complete:false};
const units={g1:{id:'g1',owner:'german',hex:edge.a},s1:{id:'s1',owner:'soviet',hex:edge.b},s2:{id:'s2',owner:'soviet',hex:edge.b}};
const context={cursor,actor:'german',state:{scenarioId:'leningrad',units}};
const battle=[{defenderHex:edge.b,attackers:['g1']}];
const declaration=rig.declare(context,battle);
A.equal(declaration.status,'declared-not-resolved');checks++;
A.deepEqual(declaration.battles[0].defenders,['s1','s2']);checks++;
A.deepEqual(rig.declare(context,[]).battles,[]);checks++;
A.deepEqual(context.state.units,units);checks++;
A.throws(()=>rig.declare(context,[...battle,...battle]),/duplicate battle/);checks++;
A.throws(()=>rig.declare(context,[{defenderHex:edge.b,attackers:['g1','g1']}]),/used twice/);checks++;
A.throws(()=>rig.declare(context,[{defenderHex:edge.b,attackers:['g1','s1']}]),/unavailable/);checks++;
A.throws(()=>rig.declare(context,[{defenderHex:edge.a,attackers:['g1']}]),/enemy-occupied/);checks++;
A.throws(()=>rig.declare(context,[{defenderHex:'9999',attackers:['g1']}]),/enemy-occupied/);checks++;
A.throws(()=>rig.declare({...context,actor:'soviet'},battle),/actor combat/);checks++;
A.throws(()=>rig.declare({...context,cursor:{...cursor,index:3}},battle),/actor combat/);checks++;
A.throws(()=>D.create({map:L,profile:P,config:{...C,scenarioId:'kiev'}}),/mismatch/);checks++;
A.throws(()=>rig.declare(context,{}),/declaration array/);checks++;
const blocked=g.edges.find(e=>e.impassable&&g.cells[e.a].verified&&g.cells[e.b].verified);
if(blocked){const bad={...context,state:{scenarioId:'leningrad',units:{g1:{id:'g1',owner:'german',hex:blocked.a},s1:{id:'s1',owner:'soviet',hex:blocked.b}}}};A.throws(()=>rig.declare(bad,[{defenderHex:blocked.b,attackers:['g1']}]),/blocked/);checks++;}
console.log(`PASS Leningrad setup readiness and bounded combat declarations ${checks} assertions`);

'use strict';
const A=require('node:assert/strict');
const H=require('../core/historical_movement_actions.js');
const L=require('../maps/leningrad.json');
const P=require('../maps/movement-configs/leningrad.json');
const C=require('../maps/phase-configs/leningrad.json');
const K=require('../maps/kiev.json');
const BL=require('../core/movement_binding.js');
let n=0;const ok=(v)=>{A.ok(v);n++};
const pilot=H.create({map:L,profile:P,config:C});
A.equal(pilot.metadata.hexCount,197);n++;
const b=BL.build(L,P);
const edge=b.board.edges.find(e=>e.verified&&!e.impassable&&!e.rail&&b.board.cells[e.a].verified&&b.board.cells[e.b].verified&&b.board.cells[e.b].terrain==='open');
ok(edge);
const initial={scenarioId:'leningrad',units:{g:{id:'g',owner:'german',class:'infantry',nationality:'german',size:'corps',hex:edge.a,mp:4}}};
const session={cursor:{scenarioId:'leningrad',turn:2,index:1,complete:false},actor:'german',state:initial};
const request={unitId:'g',path:[edge.a,edge.b]};
ok(pilot.legal(session,request));
const result=pilot.execute(session,request);
ok(result.ok);A.equal(result.state.units.g.hex,edge.b);n++;
A.equal(initial.units.g.hex,edge.a);n++;
A.equal(result.result.to,edge.b);n++;
A.deepEqual(result.state.units.g,{...initial.units.g,hex:edge.b});n++;
A.throws(()=>pilot.execute({...session,actor:'soviet'},request),/Wrong phase actor/);n++;
A.throws(()=>pilot.execute({...session,cursor:{...session.cursor,index:2}},request),/not permitted/);n++;
const blocked=pilot.execute(session,{unitId:'g',path:[edge.a,'9999']});
A.equal(blocked.ok,false);A.equal(blocked.reason,'illegal-action');n+=2;
A.equal(initial.units.g.hex,edge.a);n++;
const enemy={id:'s',owner:'soviet',class:'infantry',size:'corps',hex:edge.b,mp:4};
const occupied=pilot.execute({...session,state:{...initial,units:{...initial.units,s:enemy}}},request);
A.equal(occupied.ok,false);n++;
A.throws(()=>H.create({map:K,profile:P,config:C}),/not-gameplay-certified/);n++;
A.throws(()=>H.create({map:L,profile:P,config:{...C,scenarioId:'kiev'}}),/mismatch/);n++;
A.throws(()=>pilot.execute({...session,state:{...initial,scenarioId:'kiev'}},request),/mismatch/);n++;
A.throws(()=>pilot.execute({...session,state:{...initial,units:{g:{...initial.units.g,id:'fake'}}}},request),/Malformed/);n++;
console.log(`PASS Leningrad phase/movement pilot ${n} checks (no historical scenario activation)`);

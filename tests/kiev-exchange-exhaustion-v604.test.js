'use strict';
const assert=require('node:assert/strict');
const req=p=>require('../'+p);
const Campaign=req('core/historical_campaign_session');
const Auto=req('core/historical_campaign_autoplay');
const F=require('./fixtures/kiev-source-opening-v437');
const map=F.map, counterConfig=F.counterConfig;
const profile=require('../maps/movement-configs/kiev.json'), config=require('../maps/phase-configs/kiev.json');
const combatPolicy=require('../maps/combat-configs/kiev.json'), buildupPolicy=require('../maps/buildup-configs/kiev.json'), housekeepingPolicy=require('../maps/housekeeping-configs/kiev.json');
const committed=require('../core/historical_deployment_session').create({map,setupSpec:F.setupSpec,counterConfig,inventory:F.inventory,phaseConfig:config,movementProfile:profile,phaseFactories:{combat:()=>({})},allocation:F.allocation,placements:F.placements}).commit();
const ctx={...committed.opening,map,profile,config,counterConfig,combatPolicy,enableAirSupport:true,buildupPolicy,buildupAllocation:committed.allocation,housekeepingPolicy};
const context=ctx;
context.combatPolicy={...context.combatPolicy,crtVariant:'advanced'};
const audit=req('rules/audit/kiev-seeded-blocker-v603.json');
const replay=Campaign.restore(audit.save,context);
assert.deepEqual(replay.snapshot(),audit.snapshot);
const before=replay.snapshot();
const decision=Auto.decide({session:replay,context,policy:{seed:42,selectionMode:'seeded',maxCombatPhases:14}});
assert.equal(decision.status,'action');
assert.equal(decision.action.action.type,'resolve-battle');
assert.equal(decision.action.action.die,3);
assert.deepEqual(decision.action.action.choices.attackerLossIds,['kiev-front-r05c01']);
assert.equal(decision.action.action.choices.advanceUnitId,undefined);
const result=replay.execute(decision.action);
assert.equal(result.event.outcome,'EX');
assert.equal(result.session.snapshot().state.units['kiev-front-r05c01'],undefined);
assert.equal(result.event.losses.find(l=>l.unitId==='kiev-front-r05c01').attackPoints,2);
assert.equal(result.event.losses.find(l=>l.unitId==='kiev-front-r02c02').defensePoints,3);
assert.equal(result.event.advanced,null);
assert.equal(result.session.snapshot().state.units['kiev-front-r02c02']?.printedCombatStrength,3);
assert.notEqual(result.session.snapshot().state.units['kiev-front-r02c02']?.hex,'0303');
assert.throws(()=>replay.execute({...decision.action,action:{...decision.action.action,choices:{...decision.action.action.choices,advanceUnitId:'kiev-front-r05c01'}}}));
assert.deepEqual(replay.snapshot(),before);
assert.deepEqual(Campaign.restore(result.session.save(),context).snapshot(),result.session.snapshot());
console.log('PASS original blocked campaign: legal EX, losses, no advance, exact replay');

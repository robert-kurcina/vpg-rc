const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const get=p=>fs.readFileSync(path.join(root,p),'utf8');
const registry=JSON.parse(get('maps/presentation/registry.json'));
const report=get('references/ux/oberlabs/SOURCE_COMPARISON.md');
const wrapper=get('legacy/oberlabs-play.js');
const ui=get('legacy/ui.js');
const generic=get('app.js');
assert.equal(registry.implementationStatus.startsWith('declarative-contract-only'),true);
assert.equal(Object.keys(registry.games).length,5);
assert.equal(registry.upstreamB4mBaseline.combatSelection,'defender-first');
assert.equal(registry.upstreamB4mBaseline.referenceTabs.length,4);
assert.ok(registry.requiredActionContract.includes('undo'));
assert.ok(wrapper.includes("details.id='ol-rules-dialog'"));
assert.ok(!wrapper.includes('terrain-effects-tab'), 'local wrapper is not yet the four-tab upstream UI');
assert.ok(ui.includes("selection={type:'defender'"), 'B4M legacy selects defender first');
assert.ok(generic.includes('Attackers:'), 'generic implementation selects attackers first');
assert.match(report,/upstream JavaScript was not located/i);
assert.match(report,/GAP:.*common tabbed reference window/i);
console.log('PASS: source-traced UX contract; B4M/local-generic divergence and missing tabs explicitly tracked');

'use strict';
const assert=require('node:assert/strict');
const G=require('../core/map_movement_graph');
const Binding=require('../core/movement_binding');
const Geo=require('../core/historical_combat_geography');
const map=require('../maps/arduous.json');
const policy=require('../maps/movement-configs/arduous.json');
const evidence=require('../maps/movement-configs/source-reviewed-edge-ledgers.json').maps[map.id];
const audit=require('../rules/audit/arduous-river-candidates-v418.json');
let checks=0;const check=(condition,description)=>{assert.ok(condition,description);checks++};
const board=G.build(map),bound=Binding.build(map,policy);
check(board.edges.length===413&&Object.keys(board.cells).length===155,'physical grid');
check(board.edges.filter(e=>e.rail).length===85,'registered railway links');
check(board.edges.filter(e=>e.river).length===45,'confirmed river hexsides');
check(board.edges.every(e=>e.verified&&!e.impassable),'every physical edge source-authorized');
check(bound.metadata.riverEdges===45&&bound.metadata.railEdges===85,'shared movement/hexside ledgers agree');
const key=e=>[e.a,e.b].sort().join(':');
check(JSON.stringify(board.edges.filter(e=>e.river).map(key).sort())===JSON.stringify(evidence.riverEdges.slice().sort()),'exact confirmed river set');
check(JSON.stringify(board.edges.filter(e=>e.rail).map(key).sort())===JSON.stringify(evidence.railEdges.slice().sort()),'exact source rail set');
check(audit.sideObservations.filter(e=>e.internalPair).length===45,'source river review 45 confirmed candidates');
const river=board.edges.find(e=>e.river&&!map.cells.find(c=>c.id===e.b).tileMarkers?.some(x=>x.kind==='city'));
const dry=board.edges.find(e=>!e.river&&!e.rail&&!map.cells.find(c=>c.id===e.b).tileMarkers?.some(x=>x.kind==='city'));
check(Boolean(river&&dry),'river and nonriver checks available');
const geography=Geo.create(map,policy,{cityMarkerMode:'source-typed-v1'});
for(const [edge,expected] of [[river,true],[dry,false]]){
 const result=geography.evaluate({attackers:['test'],defenderHex:edge.b},{test:{hex:edge.a}});
 check(result.allAttackersAcrossRiver===expected,'combat river crossing '+expected);
 check(result.evidence.crossings[0].source==='arduous-svg-reviewed-v419','shared source provenance');
}
const units={test:{id:'test',owner:'german',class:'infantry',size:'corps',mp:4,hex:'0106'}};
const moved=Binding.move(bound,{kind:'movement',owner:'german'},units,2,{unitId:'test',path:['0106','0207']});
check(moved.ok&&moved.cost===1,'rail movement through native shared rules');
const no=Binding.move(bound,{kind:'movement',owner:'german'},units,2,{unitId:'test',path:['0106','0305']});
check(!no.ok&&no.reason==='unverified-connection','nonadjacent movement rejected');
const altered=(mutation,match)=>{const m=structuredClone(map);mutation(m);assert.throws(()=>G.build(m),match);checks++};
altered(m=>{m.cells[0].terrain='forest'},/fingerprint-mismatch/);
altered(m=>{m.geometry.columnParityDown='even'},/fingerprint-mismatch/);
altered(m=>{m.hexCenterRailConnections.pop()},/fingerprint-mismatch/);
altered(m=>{m.cells[0].terrainStatus='invented'},/fingerprint-mismatch/);
altered(m=>{m.authoredSourceVectors.sourceSvgSha256='invented'},/fingerprint-mismatch/);
const kiev=require('../maps/kiev.json');check(G.build(kiev).edges.length===442,'Kiev separately source-authorized for experimental gameplay');
console.log('PASS Arduous executable graph',checks,'checks (155 hexes, 85 rails, 45 river sides)');

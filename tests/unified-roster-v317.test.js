const assert=require('node:assert/strict');
const fs=require('node:fs');
const L=require('../maps/rosters/loader');
const R=require('../core/roster');
const reg=require('../maps/registry.json');
const scenarios=['battle-for-moscow','arduous','leningrad','kiev','kiev-odessa'];
assert.deepEqual(L.list().map(x=>x.id),scenarios);
assert.deepEqual(reg.maps.map(x=>x.id),scenarios);
const expected=[39,26,20,27,35];
scenarios.forEach((id,i)=>{
 const units=L.load(id);const check=L.validate(units);
 assert.ok(check.ok,JSON.stringify(check.errors));assert.equal(units.length,expected[i]);
 assert.equal(check.executable,id==='battle-for-moscow'?39:0);
 assert.equal(new Set(units.map(u=>u.id)).size,units.length);
 units.forEach(u=>{
  assert.equal(u.schemaVersion,1);assert.equal(typeof u.artwork.display,'string');
  assert.equal(u.scenario,id==='kiev-odessa'&&u.id.startsWith('kiev/print/')?'kiev':id);
  if(!u.executable)assert.equal(u.historicalUnitId,null);
 });
 const files=JSON.parse(fs.readFileSync('maps/rosters/registry.json','utf8'));
 assert.equal(files.entries[i].id,id);
 assert.equal(reg.maps[i].unitRoster.rosterId,id);
 assert.equal(reg.maps[i].unitRoster.loader,'maps/rosters/loader.js');
});
const b=L.load('battle-for-moscow');
const raw=require('../games/battle-for-moscow/units.json').units;
assert.deepEqual(b.map(x=>x.rawRef).sort(),raw.map(x=>x.id).sort());
const od=L.load('kiev-odessa');
assert.equal(od.filter(x=>x.sourceKind==='scenario-design').length,8);
assert.equal(od.filter(x=>x.sourceKind==='printed-pair').length,27);
assert.equal(od.filter(x=>x.artwork.singleSided).length,3);
assert.equal(od.find(x=>x.id==='kiev-odessa/romanian-air-support').deployment.turn,2);
assert.equal(od.find(x=>x.id==='kiev-odessa/soviet-black-sea-fleet').deployment.hex,'1513');
assert.equal(R.select(od,{sourceKind:'scenario-design'}).length,8);
assert.throws(()=>R.compose(b,[b[0]]),/duplicate ID/i);
assert.equal(R.validate([{...b[0],artwork:{front:null,back:null,display:null}}]).ok,false);
assert.equal(R.validate([{...b[0],executable:true,characteristics:null}]).ok,false);
assert.throws(()=>L.load('odessa-extension'),/Unknown roster/);
console.log('PASS shared roster: five historical configurations; 39 canonical, 73 source-matched, 8 Odessa designs; strict validation');

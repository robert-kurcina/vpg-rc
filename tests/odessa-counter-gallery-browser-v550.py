#!/usr/bin/env python3
"""Actual Chromium evaluation of shared-engine original Kiev–Odessa counter gallery.
No images are generated by a separate art system or cropped from counter sheets.
"""
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
html=(ROOT/'rules/audit/visual/kiev-odessa-source-counter-gallery-v550.html').read_text()
OUT=ROOT/'rules/audit/visual'
checks=0
def ok(x,why):
 global checks
 assert x,why
 checks+=1
with sync_playwright() as pw:
 browser=pw.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1100,'height':1000},device_scale_factor=1)
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content(html,wait_until='load',timeout=60000)
 ok(page.locator('[data-gallery-unit]').count()==47,'36 opening + seven later ground and four Support original units')
 ok(page.locator('[data-gallery-category="untried"]').count()==10,'Ten untried mechanized')
 ok(page.locator('[data-gallery-category="single-sided"]').count()==3,'Three reverse-only cavalry')
 ok(page.locator('[data-gallery-category="two-step"]').count()==30,'30 two-step ground faces including later arrivals')
 ok(page.locator('[data-gallery-category="support"]').count()==4,'Four Support counters')
 ok(page.locator('[data-gallery-unit^="original-reserve:"]').count()==7,'All seven later originals present')
 ok(page.locator('img').count()==0,'No bitmap source-photo crops anywhere')
 for unit in ['kiev-odessa/romanian-cavalry-corps','kiev-odessa/soviet-cavalry-corps-a','kiev-odessa/soviet-cavalry-corps-b']:
  row=page.locator(f'[data-gallery-unit="{unit}"]')
  ok(row.count()==1,'One gallery unit: '+unit)
  left=row.locator('xpath=following-sibling::*[1]')
  right=row.locator('xpath=following-sibling::*[2]')
  ok(left.locator('[data-damaged="false"]').count()==1,'Single-sided cavalry rendered undamaged: '+unit)
  ok(left.locator('[data-role="status_reduced"]').evaluate('e=>getComputedStyle(e).display')=='none','Cavalry has no damage stripe: '+unit)
  ok(right.locator('.eliminated').count()==1,'No fabricated reduced face: '+unit)
  ok(right.locator('.ground-counter-svg').count()==0,'No duplicate or invented reduced art: '+unit)
 mech=page.locator('[data-gallery-category="untried"]').first
 left=mech.locator('xpath=following-sibling::*[1]')
 right=mech.locator('xpath=following-sibling::*[2]')
 ok(left.locator('[data-damaged="false"]').count()==1,'Untried Corps undamaged')
 ok(right.locator('[data-damaged="false"]').count()==1,'Revealed one-step Corps undamaged')
 ok(right.locator('[data-role="status_reduced"]').evaluate('e=>getComputedStyle(e).display')=='none','Revealed Corps has no damage bar')
 genuine=page.locator('[data-gallery-category="two-step"]').first.locator('xpath=following-sibling::*[2]')
 ok(genuine.locator('[data-damaged="true"]').count()==1,'True two-step reduced counter remains marked')
 ok(genuine.locator('[data-role="status_reduced"]').evaluate('e=>getComputedStyle(e).display')=='inline','True two-step reduced counter retains damage bar')
 ok(page.locator('.support-counter-svg').count()==8,'Support uses original shared support SVG renderer')
 ok(not errors,'No browser JS exceptions '+repr(errors))
 page.screenshot(path=str(OUT/'kiev-odessa-source-counter-gallery-v550.png'),full_page=True)
 page.locator('section').last.screenshot(path=str(OUT/'kiev-odessa-support-face-gallery-v550.png'))
 small=browser.new_page(viewport={'width':375,'height':812},device_scale_factor=1)
 small.set_content(html,wait_until='load',timeout=60000)
 ok(small.evaluate('document.documentElement.scrollWidth<=window.innerWidth+1'),'375px gallery remains within viewport')
 small.screenshot(path=str(OUT/'kiev-odessa-source-counter-gallery-mobile-v550.png'),full_page=False)
 browser.close()
print('PASS v550 original source counter gallery:',checks,'Chromium assertions')

'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const T=require('../core/terrain_tiles');
const C=require('../core/canonical_hex_projection');
const H=require('../core/historical_movement_lifecycle');
const B=require('../core/movement_binding');
const S=require('../core/leningrad_preview_save');
const map=require('../maps/leningrad.json');
const movementProfile=require('../maps/movement-configs/leningrad.json');
const phaseConfig=require('../maps/phase-configs/leningrad.json');
const projectionRecord=C.project(map,c=>T.formatHexNumber(c,T.numberStyle(map,{}))).record;
const context={map,movementProfile,phaseConfig,projectionRecord};
const verified=B.build(map,movementProfile).board;
const edge=verified.edges.find(e=>e.verified&&!e.impassable&&!e.rail&&verified.cells[e.a].verified&&verified.cells[e.b].verified&&verified.cells[e.b].terrain==='open');
assert(edge);
const state={scenarioId:'leningrad',units:{g:{id:'g',owner:'german',class:'infantry',size:'corps',nationality:'german',hex:edge.a,mp:4}}};
const pilot=H.create({map,profile:movementProfile,config:phaseConfig,cursor:{scenarioId:'leningrad',turn:2,index:1,complete:false},actor:'german',state});
const moved=pilot.move({unitId:'g',path:[edge.a,edge.b]});
assert.equal(moved.ok,true);
const finished=moved.session.finish();
assert.equal(finished.ok,true);
const snapshot=finished.session.snapshot();
assert.equal(snapshot.history.length,2);
const untouched=JSON.stringify(snapshot);
assert.throws(()=>S.serialize(snapshot,context),/namespace mismatch/,'unmarked pilot is not implicitly trusted');
const envelope=S.serialize(snapshot,context,{allowUnmarkedLegacy:true});
assert.equal(S.VERSION,1);
assert.equal(envelope.version,1);
assert.equal(envelope.hexIdSpace,'legacy-physical');
assert.equal(envelope.phase.phaseId,'german-combat');
assert.equal(envelope.snapshot.history.length,2);
assert.equal(envelope.snapshot.state.hexIdSpace,'legacy-physical');
assert(envelope.snapshot.history.every(h=>h.state.hexIdSpace==='legacy-physical'));
assert.equal(JSON.stringify(snapshot),untouched,'serializing never mutates the live session');
const roundTrip=S.restore(JSON.parse(JSON.stringify(envelope)),context);
assert.deepEqual(roundTrip.snapshot,envelope.snapshot);
assert.equal(roundTrip.snapshot.history[0].state.units.g.hex,edge.a);
assert.equal(roundTrip.snapshot.history[1].state.units.g.hex,edge.b);
const canonical=S.restore(envelope,context,{targetNamespace:'canonical-preview'});
assert.equal(canonical.snapshot.state.hexIdSpace,'canonical-preview');
assert.equal(canonical.snapshot.state.units.g.hex,projectionRecord.physicalToCanonical[edge.b]);
const canonicalEnvelope=S.serialize(canonical.snapshot,context,{namespace:'canonical-preview'});
assert.deepEqual(S.restore(canonicalEnvelope,context,{targetNamespace:'legacy-physical'}).snapshot,roundTrip.snapshot);
assert.deepEqual(S.serialize(snapshot,context,{allowUnmarkedLegacy:true}),envelope,'identical saves must produce identical bytes and checksum');
const undone=S.undoPreview(envelope,context);
assert.equal(S.restore(undone,context).snapshot.cursor.index,1);
assert.equal(S.restore(undone,context).snapshot.history.length,1);
assert.deepEqual(S.restore(undone,context).snapshot.usedUnitIds,['g']);
const undoneTwice=S.undoPreview(undone,context);
assert.equal(S.restore(undoneTwice,context).snapshot.state.units.g.hex,edge.a);
assert.equal(S.restore(undoneTwice,context).snapshot.history.length,0);
assert.throws(()=>S.undoPreview(undoneTwice,context),/No movement history/);
assert.deepEqual(S.restore(S.undoPreview(canonicalEnvelope,context),context).snapshot.history.length,1);
const mutate=fn=>{const copy=structuredClone(envelope);fn(copy);return copy;};
assert.throws(()=>S.restore(mutate(x=>x.snapshot.state.units.g.hex='9999'),context),/checksum mismatch/);
assert.throws(()=>S.restore(mutate(x=>x.integrity.digest='0'.repeat(64)),context),/checksum mismatch/);
assert.throws(()=>S.restore(mutate(x=>x.version=99),context),/format\/version/);
assert.throws(()=>S.restore(mutate(x=>x.unrecognized=true),context),/envelope fields/);
assert.throws(()=>S.restore(envelope,{...context,map:{...map,id:'kiev'}}),/scenario mismatch/);
assert.throws(()=>S.restore(envelope,{...context,map:{...map,sourceStatus:'changed'}}),/incompatible boardSHA256/);
assert.throws(()=>S.restore(envelope,{...context,movementProfile:{...movementProfile,railCost:42}}),/incompatible movementSHA256/);
assert.throws(()=>S.restore(envelope,{...context,phaseConfig:{...phaseConfig,turns:9}}),/incompatible phaseSHA256/);
assert.throws(()=>S.restore(envelope,{...context,projectionRecord:{...projectionRecord,sourceCellCount:196}}),/Projection cell count mismatch|incompatible projectionSHA256/);
assert.throws(()=>S.restore(envelope,{...context,phaseConfig:null}),/Explicit board/);
assert.throws(()=>S.restore(envelope,context,{targetNamespace:'invalid'}),/Unsupported restore namespace/);
// Recompute a valid integrity digest to prove schema checks cannot be bypassed
// merely by correctly hashing a malicious or unsupported future field.
function stable(x){if(Array.isArray(x))return x.map(stable);if(x&&typeof x==='object')return Object.fromEntries(Object.keys(x).sort().map(k=>[k,stable(x[k])]));return x;}
function resign(e){const {integrity,...payload}=e;e.integrity.digest=crypto.createHash('sha256').update(JSON.stringify(stable(payload))).digest('hex');return e;}
assert.throws(()=>S.restore(resign(mutate(x=>{x.snapshot.history[0].state.units.g.futurePosition='0509'})),context),/unsupported field futurePosition/);
assert.throws(()=>S.restore(resign(mutate(x=>{x.snapshot.history[0].state.hexIdSpace='canonical-preview'})),context),/namespace mismatch/);
assert.throws(()=>S.restore(resign(mutate(x=>{x.snapshot.pendingCombat={target:'0210'}})),context),/unsupported field pendingCombat/);
assert.throws(()=>S.restore(resign(mutate(x=>{x.phase.phaseId='german-movement'})),context),/phase metadata mismatch/);
assert.throws(()=>S.restore(resign(mutate(x=>{x.snapshot.history[0].state.units.g.hex='0108'})),context),/unmapped physical hex/);
assert.throws(()=>S.restore(resign(mutate(x=>{x.snapshot.history[0].state.units.x={id:'x',hex:edge.a,owner:'german'}})),context),/roster mismatch/);
const phaseBroken=mutate(x=>{x.snapshot.history[0].cursor.index=99;});
assert.throws(()=>S.restore(resign(phaseBroken),context),/cursor outside phase configuration/);
assert.throws(()=>S.restore(resign(mutate(x=>{x.snapshot.history[0].cursor.index=2})),context),/history phase\/actor mismatch/);
assert.throws(()=>S.restore(resign(mutate(x=>{x.snapshot.cursor.index=4;x.phase.phaseId='soviet-buildup';x.phase.index=4})),context),/invalid phase completion transition/);
assert.throws(()=>S.restore(resign(mutate(x=>{x.snapshot.state.units.g.hex=edge.a})),context),/invalid phase completion transition/);
assert.throws(()=>S.restore(resign(mutate(x=>{x.snapshot.usedUnitIds=['g']})),context),/requires a prior completed movement phase/);
assert.throws(()=>S.serialize({...snapshot,pendingCombat:{target:'0410'}},context,{allowUnmarkedLegacy:true}),/unsupported field pendingCombat/);
console.log('PASS v353: versioned preview save, deterministic SHA-256, environment compatibility, movement + phase finish + two Undo steps, fail-closed tamper/future fields');

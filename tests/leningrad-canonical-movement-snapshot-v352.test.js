'use strict';
const a=require('node:assert/strict');
const T=require('../core/terrain_tiles');
const C=require('../core/canonical_hex_projection');
const M=require('../core/canonical_state_migration');
const H=require('../core/historical_movement_lifecycle');
const B=require('../core/movement_binding');
const map=require('../maps/leningrad.json');
const movement=require('../maps/movement-configs/leningrad.json');
const phase=require('../maps/phase-configs/leningrad.json');
const registry=C.project(map,c=>T.formatHexNumber(c,T.numberStyle(map,{}))).record;
const translator=M.create(registry);
// Select an actually certified, traversable edge using the production
// movement binding; this is not a fabricated synthetic draft shape.
const verified=B.build(map,movement).board;
const edge=verified.edges.find(e=>e.verified&&!e.impassable&&!e.rail&&verified.cells[e.a].verified&&verified.cells[e.b].verified&&verified.cells[e.b].terrain==='open');
a.ok(edge,'verified movement edge required');
const state={scenarioId:'leningrad',units:{g:{id:'g',owner:'german',class:'infantry',size:'corps',nationality:'german',hex:edge.a,mp:4}}};
const cursor={scenarioId:'leningrad',turn:2,index:1,complete:false};
const pilot=H.create({map,profile:movement,config:phase,cursor,actor:'german',state});
const moved=pilot.move({unitId:'g',path:[edge.a,edge.b]});
a.equal(moved.ok,true);
const snapshot=moved.session.snapshot();
a.equal(snapshot.history.length,1);
a.equal(snapshot.history[0].state.units.g.hex,edge.a);
a.equal(snapshot.state.units.g.hex,edge.b);
const before=JSON.stringify(snapshot);
a.throws(()=>translator.translateMovementSnapshot(snapshot,{direction:'toCanonical'}),/phase configuration mismatch/);
a.throws(()=>translator.translateMovementSnapshot(snapshot,{direction:'toCanonical',phaseConfig:phase}),/namespace mismatch/);
const canonical=translator.translateMovementSnapshot(snapshot,{direction:'toCanonical',allowUnmarkedLegacy:true,phaseConfig:phase});
a.equal(canonical.state.hexIdSpace,'canonical-preview');
a.equal(canonical.state.units.g.hex,registry.physicalToCanonical[edge.b]);
a.equal(canonical.history[0].state.units.g.hex,registry.physicalToCanonical[edge.a]);
a.deepEqual(canonical.history[0].cursor,snapshot.history[0].cursor);
a.equal(canonical.history[0].actor,'german');
a.deepEqual(canonical.usedUnitIds,['g']);
a.equal(JSON.stringify(snapshot),before,'input is immutable');
a.throws(()=>translator.translateMovementSnapshot(canonical,{direction:'toCanonical',phaseConfig:phase}),/namespace mismatch/);
const physical=translator.translateMovementSnapshot(canonical,{direction:'toPhysical',phaseConfig:phase});
const marked=structuredClone(snapshot);
marked.state.hexIdSpace='legacy-physical';
for(const prior of marked.history)prior.state.hexIdSpace='legacy-physical';
a.deepEqual(physical,marked,'movement state and history must round trip without information loss');
// Completed phase snapshot must preserve the *previous* movement phase in Undo.
const finished=moved.session.finish();
a.equal(finished.ok,true);
const fin=finished.session.snapshot();
a.equal(fin.history.length,2);
a.equal(fin.cursor.index,2);
const finCanon=translator.translateMovementSnapshot(fin,{direction:'toCanonical',allowUnmarkedLegacy:true,phaseConfig:phase});
a.equal(finCanon.cursor.index,2);
a.equal(finCanon.history[1].cursor.index,1);
a.deepEqual(finCanon.usedUnitIds,[]);
a.equal(finCanon.history[1].state.units.g.hex,registry.physicalToCanonical[edge.b]);
a.deepEqual(translator.translateMovementSnapshot(finCanon,{direction:'toPhysical',phaseConfig:phase}).history[1].cursor,cursor);
// Fail closed on live-movement shapes that this adapter cannot translate.
const badActor=structuredClone(snapshot);badActor.actor='soviet';
a.throws(()=>translator.translateMovementSnapshot(badActor,{direction:'toCanonical',allowUnmarkedLegacy:true,phaseConfig:phase}),/used-unit IDs/);
const badCursor=structuredClone(snapshot);badCursor.history[0].cursor.index=99;
a.throws(()=>translator.translateMovementSnapshot(badCursor,{direction:'toCanonical',allowUnmarkedLegacy:true,phaseConfig:phase}),/cursor outside phase configuration/);
const badHistory=structuredClone(snapshot);badHistory.history[0].pendingCombat={defenderHex:'0210'};
a.throws(()=>translator.translateMovementSnapshot(badHistory,{direction:'toCanonical',allowUnmarkedLegacy:true,phaseConfig:phase}),/unsupported field pendingCombat/);
const badNested=structuredClone(snapshot);badNested.state.units.g.status={retreatHex:'0210'};
a.throws(()=>translator.translateMovementSnapshot(badNested,{direction:'toCanonical',allowUnmarkedLegacy:true,phaseConfig:phase}),/nested status/);
const other=structuredClone(snapshot);other.state.units.g.hex='0108';
a.throws(()=>translator.translateMovementSnapshot(other,{direction:'toCanonical',allowUnmarkedLegacy:true,phaseConfig:phase}),/unmapped physical hex/);
a.throws(()=>translator.translateMovementSnapshot(snapshot,{direction:'toCanonical',allowUnmarkedLegacy:true,phaseConfig:{...phase,scenarioId:'kiev'}}),/configuration mismatch/);
console.log('PASS v352: real historical movement snapshot + Undo and phase finish migrate reversibly, with strict preview-only guards');

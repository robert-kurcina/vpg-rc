#!/usr/bin/env node
'use strict';
/* Checkpoint 317. Actual source-bound Kiev–Odessa combat, not a synthetic
 * state, overridden CRT, unapproved territory, or special-case game engine.
 * Inherited Kiev city marker IDs must survive the authoritative composite
 * overrides; previously Kovel combat threw "Unverified city marker identity".
 */
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const fs=require('node:fs');
const path=require('node:path');
const req=rel=>require('../'+rel);
const Compose=req('maps/composer');
const base=req('maps/kiev.json'),ext=req('maps/odessa-extension.json');
const map=Compose.compose(base,ext),published=req('maps/kiev-odessa-composite-experimental-v531.json');
const Campaign=req('core/historical_campaign_session');
const Catalog=req('core/historical_campaign_action_catalog');
const Face=req('core/historical_counter_face_projection');
const opening=req('games/kiev-odessa/experimental-preview/opening-v531.json').contextStart;
const context={...structuredClone(opening),map:published,
 profile:req('maps/movement-configs/kiev-odessa-experimental-v531.json'),
 config:req('maps/phase-configs/kiev-odessa.json'),
 counterConfig:req('maps/counter-configs/kiev-odessa-experimental-v531.json'),
 combatPolicy:req('maps/combat-configs/kiev-odessa-experimental-v531.json'),
 rosterOverlay:req('maps/roster-overlays/kiev-odessa.json'),enableAirSupport:true,
 buildupPolicy:req('maps/buildup-configs/kiev-odessa-experimental-v533.json'),
 buildupAllocation:req('games/kiev-odessa/experimental-preview/allocation-v533.json'),
 housekeepingPolicy:req('maps/housekeeping-configs/kiev-odessa-candidate-v521.json')};
let checks=0;
const eq=(a,b,why)=>{assert.deepStrictEqual(a,b,why);checks++};
const ok=(value,why)=>{assert.ok(value,why);checks++};
const bad=(fn,re,why)=>{assert.throws(fn,re,why);checks++};
const snapshotSession=s=>JSON.stringify(s.snapshot());
eq(map,published,'Published composite generated byte-equivalent map data from the shared composer');
const sourceFile='maps/source/user-svg/kiev-odessa-main.svg';
const bytes=fs.readFileSync(sourceFile);
eq(crypto.createHash('sha256').update(bytes).digest('hex'),map.authoritativeSourceGeometry.sha256,
 'Authoritative composite SHA-256 still binds the original user-supplied SVG');
const svg=bytes.toString('utf8');
let inherited=0,restored=0;
for(const c of map.cells){
 const previous=base.cells.find(x=>x.id===c.id);
 for(const marker of (c.tileMarkers||[]).filter(m=>['city','majorCity'].includes(m.kind))){
  ok(marker.sourceSvgId,'Composed city has verifiable SVG marker '+c.id);
  ok(svg.includes('id="'+marker.sourceSvgId+'"'),'City marker original source SVG use exists '+c.id);
  if(previous?.tileMarkers?.some(x=>x.kind===marker.kind&&x.label===marker.label)){
   inherited++;
   if(ext.authoritativeCellOverrides?.[c.id]?.tileMarkers?.some(x=>x.kind===marker.kind&&x.label===marker.label&&!x.sourceSvgId))restored++;
   const prior=previous.tileMarkers.find(x=>x.kind===marker.kind&&x.label===marker.label);
   eq(marker.sourceSvgId,prior.sourceSvgId,'Inherited Kiev marker remains exact source ID '+c.id);
  }
 }
}
eq(inherited,16,'All sixteen Kiev city source identities retained');
eq(restored,15,'Fifteen absent composite city SVG IDs are restored, not guessed');
// Altered labels and SVG hashes MUST NOT inherit a nearby source ID. No
// fallback to heuristic city matching or an unverified source identifier.
const altered=structuredClone(base);
altered.cells.find(c=>c.id==='0502').sourceTerrainEvidence.sourceSvgSha256='f'.repeat(64);
const untrusted=Compose.compose(altered,ext);
ok(!untrusted.cells.find(c=>c.id==='0502').tileMarkers.find(m=>m.kind==='city').sourceSvgId,
 'Forged source hash cannot authorize a city ID');
const renamed=structuredClone(base);
renamed.cells.find(c=>c.id==='0502').tileMarkers.find(m=>m.kind==='city').label='Not Kovel';
const wrongCity=Compose.compose(renamed,ext);
ok(!wrongCity.cells.find(c=>c.id==='0502').tileMarkers.find(m=>m.kind==='city').sourceSvgId,
 'Mismatched city label cannot inherit another city source ID');
const forgedOverride=structuredClone(ext);
forgedOverride.authoritativeCellOverrides['0502'].city.name='Forged Kovel';
const wrongOverride=Compose.compose(base,forgedOverride);
ok(!wrongOverride.cells.find(c=>c.id==='0502').tileMarkers.find(m=>m.kind==='city').sourceSvgId,
 'Composite override city-name inconsistency never inherits source identity');
const added=structuredClone(context);
added.map=structuredClone(map);added.map.cells.find(c=>c.id==='0502').tileMarkers.find(m=>m.kind==='city').sourceSvgId='invented-marker';
bad(()=>Campaign.create(added),/fingerprint-mismatch/i,'Edited source IDs invalidate signed map authorization');
let session=Campaign.create(context);const step=a=>{session=session.execute(a).session;return session.snapshot()};
const before=()=>session.snapshot();
eq(before().phaseId,'german-combat');
eq(before().state.cityControl.Kovel,'soviet');
step({type:'combat',action:{type:'finish-air-sea'}});
const defender='kiev-front-r05c02',german='kiev-front-r02c03',soviet='kiev-front-r03c05';
const declaration={defenderHex:'0502',attackers:[german]};
ok(Catalog.discover({session,context,enumerateCombinedPlans:false}).proposals.some(x=>JSON.stringify(x)===JSON.stringify(declaration)),
 'Original German assault on Kovel is a live catalogue proposal');
step({type:'combat',action:{type:'commit-battles',battles:[declaration]}});
step({type:'combat',action:{type:'select-battle',defenderHex:'0502'}});
step({type:'combat',action:{type:'commit-ground-air',faceId:null}});
const beforeRoll=before(),beforeRollSave=session.save(),rollDigest=snapshotSession(session);
const outcomes=[];
for(let die=1;die<=6;die++){
 const opts=Catalog.discoverPostRoll({session,context,die});
 ok(opts.options.length>0,'Source-valid result(s) for die '+die);
 eq(snapshotSession(session),rollDigest,'Post-roll discovery is read-only for die '+die);
 outcomes.push(opts.crtOutcome);
 for(const result of opts.options){
  eq(result.action.action.die,die,'Committed consequence has exact die '+die);
  const trial=session.execute(result.action);
  eq(trial.event.outcome,opts.crtOutcome,'Authoritative EX/DR/NE/AL receipt matches preview');
  eq(trial.session.undo().session.snapshot(),beforeRoll,'Undo each source-valid consequence '+die);
  eq(Campaign.restore(trial.session.save(),context).snapshot(),trial.session.snapshot(),
   'Authenticated replay of each complete combat consequence '+die);
 }
}
eq(outcomes,['DR','EX','EX','NE','NE','AL'],'Common B4M CRT outcomes for original Kovel assault');
eq(session.snapshot(),beforeRoll,'Trial results never change original session');
eq(Campaign.restore(beforeRollSave,context).snapshot(),beforeRoll,'Pre-roll signed save restored');
const exchange=Catalog.discoverPostRoll({session,context,die:2});
const decline=exchange.options.find(x=>!x.advanced);
const advance=exchange.options.find(x=>x.advanced===german);
ok(decline&&advance,'Actual Exchange has legal advance and non-advance choices');
let noAdvance=session.execute(decline.action).session.snapshot();
ok(!noAdvance.state.units[defender],'EX eliminated original one-step untried Mech, not reduced it');
eq(noAdvance.state.units[german].hex,'0402','Declining advance leaves German in origin');
eq(noAdvance.state.cityControl.Kovel,'soviet','Declined advance does not capture city');
const afterEX=step(advance.action);
eq(afterEX.combat.resolved.length,1,'Original combat resolution recorded');
eq(afterEX.state.units[german].strengthStatus,'printed-reduced','Original German 6-4 infantry reduced to 3-4');
eq(Face.project(afterEX.state.units[german],context.counterConfig).side,'back','German reduced SVG uses printed reverse face');
ok(!afterEX.state.units[defender],'One-step Soviet Mechanized defender eliminated at EX');
eq(afterEX.state.units[german].hex,'0502','German advance enters exact Kovel hostCell');
eq(afterEX.state.cityControl.Kovel,'soviet','City ownership only changes at phase close');
eq(session.undo().session.snapshot(),beforeRoll,'Committed EX completely undoable');
step({type:'combat',action:{type:'finish-combat'}});
eq(before().state.cityControl.Kovel,'german','Kovel becomes German after combat phase closes');
for(const phase of ['german-special-movement','soviet-buildup','soviet-special-movement']){
 eq(before().phaseId,phase,'Correct source phase ordering');
 step(phase==='soviet-buildup'?{type:'finish-buildup'}:{type:'finish-phase'});
}
eq(before().phaseId,'soviet-combat');
const retake={defenderHex:'0502',attackers:[soviet]};
ok(Catalog.discover({session,context,enumerateCombinedPlans:false}).proposals.some(x=>JSON.stringify(x)===JSON.stringify(retake)),
 'Soviet counterattack is source-legal on original map');
step({type:'combat',action:{type:'commit-battles',battles:[retake]}});
step({type:'combat',action:{type:'select-battle',defenderHex:'0502'}});
const preRetreat=before(),preRetreatSave=session.save();
const retreat=Catalog.discoverPostRoll({session,context,die:1});
eq(retreat.crtOutcome,'DR','Soviet counterattack produces source CRT Defender Retreat');
const recapture=retreat.options.find(x=>x.advanced===soviet&&x.action.action.choices.retreatPaths?.[german]?.length===2);
ok(recapture,'Two-hex German retreat and Soviet advance sourced from actual legal catalog');
const pathTo=recapture.action.action.choices.retreatPaths[german];
bad(()=>session.execute({type:'combat',action:{type:'resolve-battle',die:1,
 choices:{retreatPaths:{[german]:['9999','8888']},advanceUnitId:soviet}}}),
 /route|retreat|invalid/i,'Forged nonadjacent retreat rejected');
eq(before(),preRetreat,'Rejected forged path is atomic');
const sovietResult=step(recapture.action);
eq(sovietResult.state.units[german].hex,pathTo.at(-1),'Defender retreats two source-connected hexes');
eq(sovietResult.state.units[soviet].hex,'0502','Soviet attacker advances into Kovel');
eq(sovietResult.state.cityControl.Kovel,'german','City does not change until second combat phase closes');
eq(session.undo().session.snapshot(),preRetreat,'Recapture undo restores pre-roll state');
eq(Campaign.restore(preRetreatSave,context).snapshot(),preRetreat,'Soviet pre-roll save authentic');
step({type:'combat',action:{type:'finish-combat'}});
eq(before().state.cityControl.Kovel,'soviet','Soviet recaptures original victory city Kovel');
step({type:'finish-phase'});
eq(before().phaseKind,'housekeeping','Original Soviet movement phase closed');
step({type:'finish-housekeeping'});
eq(before().cursor.turn,2,'City recapture retained into Turn 2');
eq(before().state.cityControl.Kovel,'soviet');
eq(Campaign.restore(session.save(),context).snapshot(),before(),'Entire real two-sided capture journal replay verified');
const sourceAudit={checkpoint:317,version:'v551',kind:'experimental-source-city-restoration-and-Kovel-capture-recapture',
 assertions:checks,cityMarkersRestored:restored,cityMarkersInherited:inherited,sourceSHA256:map.authoritativeSourceGeometry.sha256,
 mapId:map.id,fullHistoricalCertification:false,firstAttack:{hex:'0502',attacker:german,defender,die:2,outcome:'EX'},
 counterAttack:{attacker:soviet,die:1,outcome:'DR',retreat:pathTo},
 sourceMapDigest:req('maps/movement-configs/graph-sources.json').maps[map.id].mapDigest,
 compatibility:'Older campaign saves are intentionally source-fingerprint incompatible; local deployment saves are separate',
 limitations:['Experimental Kiev–Odessa graph not historically certified','No complete Romania political territory mask','Odessa naval evacuation phase remains unauthorized']};
if(process.argv.includes('--write-audit')){
 const report=path.join(__dirname,'../rules/audit/odessa-source-city-recapture-v551.json');
 fs.writeFileSync(report,JSON.stringify(sourceAudit,null,2)+'\n');
}
console.log('PASS v551 source-constrained Kovel city capture/recapture:',checks,'assertions; inherited cities',inherited,'restored',restored,'retreat',pathTo.join('→'));

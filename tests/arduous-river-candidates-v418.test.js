'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const Root=path.resolve(__dirname,'..');
const Probe=require('../core/source_topology_probe');
const Graph=require('../core/map_movement_graph');
const map=require('../maps/arduous.json');
const rails=require('../rules/audit/arduous-rail-reconciliation-v411.json');
const rivers=require('../rules/audit/arduous-river-candidates-v418.json');
const report=require('../rules/audit/arduous-topology-v418.json');
const result=Probe.build({map,railAudit:rails,riverAudit:rivers,sourceFingerprint:Probe.fingerprint(map)});
const candidate=result.edges.filter(e=>e.riverEvidence==='side-follow-candidate');
assert.equal(candidate.length,45);
assert.equal(rivers.coverage.observedHexsides,47);
assert(rivers.sideObservations.every(e=>e.classification==='side-follow-review'));
assert.deepEqual(candidate.map(e=>[e.a,e.b]),report.riverCandidatePairs);
assert(result.edges.every(e=>['side-follow-candidate','not-observed'].includes(e.riverEvidence)));
assert(result.edges.every(e=>e.verified===false));
const dirty=structuredClone(rivers);
dirty.sideObservations[0].classification='non-candidate';
assert.throws(()=>Probe.build({map,railAudit:rails,riverAudit:dirty,sourceFingerprint:Probe.fingerprint(map)}),/non-river-observation-must-not-enter-candidate-graph/);
assert.equal(Graph.build(map).metadata.riverEdges,45,'user-confirmed source topology is executable');
assert(!fs.existsSync(path.join(Root,'maps/adjudications')),'No legacy adjudication directory is needed');
assert(fs.existsSync(path.join(Root,'rules/audit/visual/arduous-river-candidates.png')));
console.log('PASS Arduous source graph: 45 river candidates, zero incident-contact entries; 12 checks');

'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const T=require('../core/terrain_tiles');
const composer=require('../maps/composer');
const kiev=require('../maps/kiev.json');
const odessa=require('../maps/odessa-extension.json');
const b=composer.compose(kiev,odessa);
const [rx,ry]=T.gridRadii(b.geometry);
const segments=T.gridSegmentData(b,rx,ry);
const sides=new Set(segments.flatMap(s=>[s.cellId+':'+s.dir,s.neighborId?s.neighborId+':'+T.OPP[s.dir]:null].filter(Boolean)));
assert.equal(odessa.sourceSeaInteriorMode,'source-registered-contours');
assert.equal(b.sourceSeaInteriorMode,'source-registered-contours');
assert.equal(b.authoredShoreHexsides.length,20);
for(const side of b.authoredShoreHexsides)assert(sides.has(side.cellId+':'+side.dir),'invalid registered hexside '+JSON.stringify(side));
assert(b.sourceWaterScanContours.polygons.length>0);
const svg=T.svgMap(b,{width:1500,height:1320,showWaterBodies:true,showGrid:true,shoreSegmentsPerSide:5});
assert(svg.includes('class="registered-source-sea-interior"'));
assert(svg.includes('class="source-registered-sea-fill"'));
assert.equal((svg.match(/class="water-shore-fringe registered-shore-fringe"/g)||[]).length,16);
assert(svg.includes('data-shore-segments="5"'));
assert(svg.includes('class="source-registered-river-geometry"'));
const off=T.svgMap(b,{width:1500,height:1320,showSourceSeaInterior:false});
assert(!off.includes('class="registered-source-sea-interior"'));
const unmodified=T.svgMap(kiev,{width:1500,height:900});
assert(!unmodified.includes('class="registered-source-sea-interior"'));
assert.equal(crypto.createHash('sha256').update(JSON.stringify(b.sourceWaterScanContours)).digest('hex'),crypto.createHash('sha256').update(JSON.stringify(odessa.sourceWaterScanContours)).digest('hex'));
console.log('PASS v287: 20 coast sides, five-segment seeded waves, opt-in connected source sea interior, river provenance, Kiev isolation');

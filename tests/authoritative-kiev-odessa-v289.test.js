'use strict';
const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const T=require('../core/terrain_tiles'), C=require('../maps/composer');
const base=JSON.parse(fs.readFileSync(path.join(root,'maps/kiev.json')));
const ext=JSON.parse(fs.readFileSync(path.join(root,'maps/odessa-extension.json')));
const b=C.compose(base,ext), src=ext.authoritativeCompositeSvg;
assert.equal(base.cells.length,165,'standalone Kiev unchanged');
assert.equal(b.cells.length,230,"definitive source hex grid");
assert.equal(new Set(b.cells.map(c=>c.id)).size,230);
for(const id of ['0818','1018','1218','1415'])assert(!b.cells.some(c=>c.id===id), 'remove obsolete '+id);
assert.equal(src.sha256,'89a5ca41af5bd34f760d9564003dfcd6fee7dbe5de7e0c07606c39d321fdcf6f');
assert.equal(src.layers.length,13);
for(const [name,n] of Object.entries({open:141,forests:52,swamp:19,minor:18,major:2,'river-minor':10,'river-major':4,coasts:7,lakes:0,railways:24,fortifications:0,deployments:9,reinforcements:2})){
 assert.equal(src.layers.find(x=>x.name===name).elementCount,n,'source layer '+name);
}
assert.equal(ext.authoritativeWaterEdgeCandidates.length,21);
assert.equal(ext.v289SourceImportAudit.unclassifiedCount,20,'source city hexes do not specify underlying terrain');
assert.equal(ext.v289SourceImportAudit.sourceGridUnmapped.length,0);
assert.equal(b.authoredShoreHexsides.length,0,'obsolete v288 coastline excluded');
assert.equal(b.compositeEntryEdges.length,0,'obsolete guessed entry edges excluded');
const report=T.validate(b,{requireReciprocal:false});assert.equal(report.errors.length,0,report.errors.join('\n'));
const svg=T.svgMap(b,{width:1290,height:1280,padding:35});
for(const marker of ['data-source-layer="river-major"','data-source-layer="river-minor"','data-source-layer="coasts"','data-source-layer="railways"','data-source-layer="reinforcements"','data-source-layer="hexgrid"'])assert(svg.includes(marker),'engine SVG '+marker);
assert.equal((svg.match(/data-hex-number="\d{4}"/g)||[]).length,230,'hex labels generated by engine');
assert(!svg.includes('class="source-registered-sea-fill"'),'no old bitmap sea');
assert(!svg.includes('class="svg-authored-river-ribbon"'),'no old Kiev/extension renderer mixed in');
assert(!svg.includes('kiev-odessa-map-scan.jpg'),'no reference scan used for engine render');
assert.equal(T.validate(base,{requireReciprocal:false}).errors.length,0,'standalone Kiev still valid');
console.log('PASS v289 definitive authored vector geometry, 230 cells, layers, water, engine labels, Kiev isolation');

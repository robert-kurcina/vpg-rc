'use strict';
const a=require('node:assert/strict');
const T=require('../core/terrain_tiles');
const P=require('../core/canonical_hex_projection');
const M=require('../core/canonical_state_migration');
const board=require('../maps/leningrad.json');
const marker=(kind)=>board.cells.flatMap(c=>(c.tileMarkers||[]).filter(m=>m.kind===kind).map(m=>({hex:c.id,kind:m.kind})));
const registry=P.project(board,c=>T.formatHexNumber(c,T.numberStyle(board,{}))).record;
const m=M.create(registry);
const markers=[...marker('cross'),...marker('star')];
a.equal(markers.length,10);
const units=Object.fromEntries(markers.map((mk,i)=>{const id='fixture-'+String(i+1).padStart(2,'0');return [id,{id,hex:mk.hex,owner:mk.kind==='cross'?'german':'soviet',kind:mk.kind==='cross'?'infantry':'army'}];}));
const state={scenarioId:'leningrad',hexIdSpace:'legacy-physical',units,turn:1,phase:'movement',side:'german'};
const before=JSON.stringify(state);
const canonical=m.translateState(state,{direction:'toCanonical'});
a.equal(canonical.hexIdSpace,'canonical-preview');
a.deepEqual(Object.keys(canonical.units),Object.keys(units));
a.equal(new Set(Object.values(canonical.units).map(u=>u.hex)).size,10);
a.deepEqual(Object.values(canonical.units).map(u=>u.hex).sort(),registry.deploymentMarkers.map(x=>x.id).sort());
a.deepEqual(m.translateState(canonical,{direction:'toPhysical'}),state);
a.equal(JSON.stringify(state),before,'input state must not mutate');
a.throws(()=>m.translateState(canonical,{direction:'toCanonical'}),/namespace mismatch/,'double translation must fail even when old/new IDs overlap');
a.throws(()=>m.translateState(state,{direction:'toPhysical'}),/namespace mismatch/);
const oldUnmarked=JSON.parse(before);delete oldUnmarked.hexIdSpace;
a.throws(()=>m.translateState(oldUnmarked,{direction:'toCanonical'}),/namespace mismatch/);
a.deepEqual(m.translateState(oldUnmarked,{direction:'toCanonical',allowUnmarkedLegacy:true}),canonical);
const sea=JSON.parse(before);sea.units['fixture-01'].hex='0108';
a.throws(()=>m.translateState(sea,{direction:'toCanonical'}),/unmapped physical hex/,'visual-only sea must not silently become gameplay hex');
const unknown=JSON.parse(before);unknown.units['fixture-01'].destination='0210';
a.throws(()=>m.translateState(unknown,{direction:'toCanonical'}),/unsupported field destination/,'unknown hex references must fail closed');
const otherState=JSON.parse(before);otherState.pendingCombat={defenderHex:'0210'};
a.throws(()=>m.translateState(otherState,{direction:'toCanonical'}),/unsupported field pendingCombat/);
const notFound=JSON.parse(before);notFound.units['fixture-01'].hex='9999';
a.throws(()=>m.translateState(notFound,{direction:'toCanonical'}),/unmapped physical hex/);
a.throws(()=>M.create({...registry,canonicalToPhysical:{...registry.canonicalToPhysical,'0109':'0410'}}),/Non-bijective/);
a.throws(()=>M.create({...registry,errors:['source numbering unverified']}),/error-free/);
const nested=JSON.parse(before);nested.units['fixture-01'].status={fallbackHex:'0209'};
a.throws(()=>m.translateState(nested,{direction:'toCanonical'}),/nested status/);
const nestedState=JSON.parse(before);nestedState.side={owner:'german',hex:'0210'};
a.throws(()=>m.translateState(nestedState,{direction:'toCanonical'}),/Invalid state actor/);
const prior={...JSON.parse(before),turn:1};
const draft={scenarioId:'leningrad',cursor:{scenarioId:'leningrad',turn:1,index:1,complete:false},state:JSON.parse(before),history:[{state:prior,usedUnitIds:['fixture-01']}],usedUnitIds:['fixture-02']};
const immutable=JSON.stringify(draft);
const migrated=m.translateDraft(draft,{direction:'toCanonical'});
a.equal(migrated.state.hexIdSpace,'canonical-preview');
a.equal(migrated.history[0].state.hexIdSpace,'canonical-preview');
a.deepEqual(m.translateDraft(migrated,{direction:'toPhysical'}),draft);
a.equal(JSON.stringify(draft),immutable);
const pending={...draft,declaredBattles:[{defenderHex:'0210'}]};
a.throws(()=>m.translateDraft(pending,{direction:'toCanonical'}),/unsupported field declaredBattles/);
const altered={...draft,history:[{state:{...prior,units:{...prior.units,extra:{id:'extra',hex:'0108'}}},usedUnitIds:[]}]};
a.throws(()=>m.translateDraft(altered,{direction:'toCanonical'}),/unmapped physical hex/);
const tampered={...draft,history:[{state:prior,usedUnitIds:['not-a-unit']}]};
a.throws(()=>m.translateDraft(tampered,{direction:'toCanonical'}),/history used-unit IDs/);
a.equal(m.recordStatus,'PREVIEW_ONLY');
console.log('PASS v351: reversible 10-marker canonical state and history preview, namespace guarding, fail-closed unsupported references, visual-only rejection');

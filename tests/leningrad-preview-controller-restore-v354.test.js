'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const T=require('../core/terrain_tiles');
const Projection=require('../core/canonical_hex_projection');
const H=require('../core/historical_movement_lifecycle');
const Binding=require('../core/movement_binding');
const Save=require('../core/leningrad_preview_save');
const Preview=require('../core/leningrad_preview_controller');
const map=require('../maps/leningrad.json');
const movementProfile=require('../maps/movement-configs/leningrad.json');
const phaseConfig=require('../maps/phase-configs/leningrad.json');
const projectionRecord=Projection.project(map,c=>T.formatHexNumber(c,T.numberStyle(map,{}))).record;
const context={map,movementProfile,phaseConfig,projectionRecord};
const graph=Binding.build(map,movementProfile).board;
const edge=graph.edges.find(e=>e.verified&&!e.impassable&&!e.rail&&graph.cells[e.a].verified&&graph.cells[e.b].verified&&graph.cells[e.b].terrain==='open');
assert(edge,'requires a real verified movement edge');
const original={scenarioId:'leningrad',units:{g:{id:'g',owner:'german',class:'infantry',size:'corps',nationality:'german',hex:edge.a,mp:4}}};
const initial=H.create({map,profile:movementProfile,config:phaseConfig,cursor:{scenarioId:'leningrad',turn:2,index:1,complete:false},actor:'german',state:original});
const first=initial.move({unitId:'g',path:[edge.a,edge.b]});
assert.equal(first.ok,true);
const finished=first.session.finish();
assert.equal(finished.ok,true);
assert.equal(finished.nextPhase,'german-combat');
const envelope=Save.serialize(finished.session.snapshot(),context,{allowUnmarkedLegacy:true});
const originalBytes=JSON.stringify(envelope);
const loaded=Preview.restore(JSON.parse(originalBytes),context);
const expected=Save.restore(envelope,context).snapshot;
assert.deepEqual(loaded.snapshot(),expected,'the controller must retain the exact validated state and Undo history');
assert.equal(loaded.snapshot().cursor.index,2,'restore remains in unsupported combat phase');
assert.throws(()=>loaded.move({unitId:'g',path:[edge.b,edge.a]}),/Only movement-phase pilot supported/);
assert.throws(()=>loaded.finish(),/Only movement-phase pilot supported/);
assert.deepEqual(loaded.snapshot(),expected,'rejected operations must not mutate restored snapshot');
const afterFinishUndo=loaded.undo();
assert.equal(afterFinishUndo.ok,true);
assert.equal(afterFinishUndo.session.snapshot().cursor.index,1);
assert.deepEqual(afterFinishUndo.session.snapshot().usedUnitIds,['g']);
assert.equal(afterFinishUndo.session.move({unitId:'g',path:[edge.b,edge.a]}).ok,false,'already moved unit stays spent after Undo of phase finish');
const afterMoveUndo=afterFinishUndo.session.undo();
assert.equal(afterMoveUndo.ok,true);
assert.equal(afterMoveUndo.session.snapshot().state.units.g.hex,edge.a);
assert.deepEqual(afterMoveUndo.session.snapshot().usedUnitIds,[]);
assert.equal(afterMoveUndo.session.snapshot().history.length,0);
const resumed=afterMoveUndo.session.move({unitId:'g',path:[edge.a,edge.b]});
assert.equal(resumed.ok,true,'movement must resume through the real rules evaluator');
assert.equal(resumed.session.snapshot().state.units.g.hex,edge.b);
const persisted=Preview.save(resumed.session,context);
assert.equal(persisted.hexIdSpace,'legacy-physical');
assert.equal(persisted.snapshot.history.length,1);
assert.deepEqual(Preview.restore(JSON.parse(JSON.stringify(persisted)),context).snapshot(),Save.restore(persisted,context).snapshot);
assert.equal(Preview.restore(persisted,context).finish().nextPhase,'german-combat');
const noHistory=Preview.restore(Preview.save(afterMoveUndo.session,context),context).undo();
assert.equal(noHistory.ok,false);
assert.equal(noHistory.reason,'nothing-to-undo');
assert.equal(JSON.stringify(envelope),originalBytes,'restore cannot mutate input envelope');
const leaked=loaded.snapshot();leaked.state.units.g.hex='9999';
assert.equal(loaded.snapshot().state.units.g.hex,edge.b,'controller snapshot is detached');
assert.throws(()=>Preview.restore({...envelope,scenarioId:'kiev'},context),/format\/version/);
assert.throws(()=>Preview.restore({...envelope,integrity:{...envelope.integrity,digest:'0'.repeat(64)}},context),/checksum mismatch/);
assert.throws(()=>Preview.restore(envelope,{...context,movementProfile:{...movementProfile,source:'different'}}),/incompatible movementSHA256/);
const canonical=Save.restore(envelope,context,{targetNamespace:'canonical-preview'}).snapshot;
const canonicalEnvelope=Save.serialize(canonical,context,{namespace:'canonical-preview'});
assert.throws(()=>Preview.restore(canonicalEnvelope,context),/requires legacy-physical save/);
const stable=x=>Array.isArray(x)?x.map(stable):x&&typeof x==='object'?Object.fromEntries(Object.keys(x).sort().map(k=>[k,stable(x[k])])):x;
const resign=e=>{const {integrity,...payload}=e;e.integrity.digest=crypto.createHash('sha256').update(JSON.stringify(stable(payload))).digest('hex');return e;};
const forged=structuredClone(envelope);
forged.snapshot.history[0].state.units.g.mp=100; // not an effect of move()
assert.throws(()=>Preview.restore(resign(forged),context),/Restored movement state progression mismatch/);
const missingPrior=structuredClone(envelope);
missingPrior.snapshot.history.shift();
assert.throws(()=>Preview.restore(resign(missingPrior),context),/history length mismatch|history progression|used-unit progression/);
assert.throws(()=>Preview.save({},context),/Movement controller required/);
console.log('PASS v354: verified v353 save -> isolated movement controller, blocked post-phase actions, two Undo steps, resumed rules-backed move, and strict rejection of invalid saves');

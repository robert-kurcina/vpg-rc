'use strict';
const A=require('node:assert/strict');
const C=require('../maps/counter-configs/leningrad.json');
const R=require('../core/leningrad_counter_roster.js');
const result=R.inspect(C);
A.equal(result.valid,true,JSON.stringify(result.errors));
A.equal(result.germanGroundFaceCount,11);
A.equal(result.specialGroundMarkers.length,1);
A.equal(result.specialGroundMarkers[0].printedIdentifier,"WMM");
A.equal(result.infantryFaceCount,9);
A.equal(result.panzerFaceCount,2);
A.equal(result.reinforcementCandidateFaceIds.length,6);
A.equal(result.possibleReinforcementPairs.length,15);
A.equal(result.selectedReinforcementPair,null);
A.equal(result.historicalRosterAuthorized,false);
A.equal(result.units.filter(u=>u.kind==='tank').length,2);
A.ok(result.units.every(u=>u.sourceStatus==='unverified'));
const corrupt=JSON.parse(JSON.stringify(C));
const front=corrupt.faces.front.find(f=>f.faceId==='leningrad-front-r03c01');
const back=corrupt.faces.back.find(f=>f.faceId===front.pairedFaceId);
back.visualTranscription.printedValues='12-6';
A.match(R.inspect(corrupt).errors.join('\n'),/Front\/back mismatch/);
const missing=JSON.parse(JSON.stringify(C));
missing.faces.back=missing.faces.back.filter(f=>f.faceId!==front.pairedFaceId);
A.match(R.inspect(missing).errors.join('\n'),/Missing back face/);
A.throws(()=>R.inspect({}),/configuration/);
console.log('PASS Leningrad counter roster: 12 structural/negative assertions');

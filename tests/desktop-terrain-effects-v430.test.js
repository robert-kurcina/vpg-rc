'use strict';
const assert=require('node:assert/strict');
const T=require('../core/terrain_tooltips');
const D=require('../core/game_display_settings');
const kiev=require('../maps/movement-configs/kiev.json');
const combat=require('../maps/combat-configs/arduous.json');
const board=require('../maps/battle-for-moscow.json');
let n=0;
assert.deepEqual(D.DEFAULT,{largerCounters:false,showCoast:true,coastWavelets:true,terrainTooltips:true});n++;
assert.deepEqual(D.normalize({terrainTooltips:false}),{largerCounters:false,showCoast:true,coastWavelets:true,terrainTooltips:false});n++;
const labels=T.describe({id:'0403',terrain:'open',tileEdges:{}},{movement:kiev,combat});
assert.match(labels,/0403 · Open/);assert.match(labels,/Movement: 1 MP to enter/);assert.match(labels,/No terrain odds-column modifier/);n+=3;
const river=T.describe({id:'0404',terrain:'forest',tileEdges:{NE:[{kind:'majorRiver'},{kind:'rail'}]}},{movement:kiev,combat});
assert.match(river,/Major River sides:/);assert.match(river,/\+1 MP when crossing off rail/);assert.match(river,/Rail sides:/);assert.match(river,/Combat: -1 attacker odds column/);n+=4;
const source=T.describe({id:'0211',terrain:'open',tileMarkers:[{kind:'fortification'}]},{movement:kiev,combat});
assert.match(source,/Fortification: -1 attacker odds column/);assert.match(source,/Soviet defender only/);n+=2;
const b4mForest=board.cells.find(c=>c.terrain==='forest');
assert(b4mForest);const b4m=T.describe(b4mForest,{movement:{terrainCosts:{forest:2}},combat:{terrainShifts:{forest:1}}});
assert.match(b4m,/Movement: 2 MP to enter/);assert.match(b4m,/Combat: -1 attacker odds column/);n+=3;
console.log(`PASS desktop terrain source-tooltip effects and Settings: ${n} assertions`);
